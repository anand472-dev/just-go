#!/bin/sh
# Records upstream's integration tests as the conformance corpus.
# Output: conformance/corpus/cases.jsonl and conformance/corpus/README.md.
# Needs oracle/src (run scripts/build-oracle.sh first), cargo, patch, and jq.
set -eu

# Run from the repository root regardless of the caller's directory.
cd "$(dirname "$0")/.."
ROOT=$(pwd)

for tool in cargo patch jq tar; do
	command -v "$tool" >/dev/null 2>&1 || {
		echo "record-corpus: $tool is required" >&2
		exit 1
	}
done
[ -d oracle/src ] || {
	echo "record-corpus: oracle/src is missing; run scripts/build-oracle.sh" >&2
	exit 1
}
[ -x oracle/bin/just ] || {
	echo "record-corpus: oracle/bin/just is missing; run scripts/build-oracle.sh" >&2
	exit 1
}

SCRATCH=$(mktemp -d "${TMPDIR:-/tmp}/just-go-corpus.XXXXXX")
trap 'rm -rf "$SCRATCH"' EXIT INT TERM

# 1. Copy oracle/src out of the repository. The git metadata is left behind;
# target/ comes along so the dependency builds are reused.
mkdir "$SCRATCH/src"
(cd oracle/src && tar --exclude=./.git -cf - .) | (cd "$SCRATCH/src" && tar -xf -)

# 2. Patch the copy so Test::status appends one JSON line per call.
(cd "$SCRATCH/src" && patch -p1 <"$ROOT/scripts/recorder.patch")

# 3. Run upstream's tests. Some may fail on this platform; the recorder
# captures a case before the comparison runs, so that is acceptable.
RAW="$SCRATCH/raw.jsonl"
: >"$RAW"
# The recorder lists the ids of cases that lost an input here.
: >"$RAW.lossy"
if ! (cd "$SCRATCH/src" && JUST_RECORD_FILE="$RAW" cargo test --release); then
	echo "record-corpus: cargo test reported failures; continuing with the recorded cases" >&2
fi
[ -s "$RAW" ] || {
	echo "record-corpus: no cases were recorded" >&2
	exit 1
}

# 4. Sort by id and drop exact duplicates.
OUT=conformance/corpus/cases.jsonl
mkdir -p conformance/corpus
jq -sc 'sort_by(.id)
	| reduce .[] as $c ([]; if length > 0 and .[-1] == $c then . else . + [$c] end)
	| .[]' "$RAW" >"$SCRATCH/cases.jsonl"
mv "$SCRATCH/cases.jsonl" "$OUT"

# 5. Write the counts and the oracle version.
TOTAL=$(wc -l <"$OUT" | tr -d ' ')
REGEX=$(jq -s '[.[] | select(.stdout_regex != null or .stderr_regex != null)] | length' "$OUT")
RESPONSE=$(jq -s '[.[] | select(.response != null)] | length' "$OUT")
CACHED=$(jq -s '[.[] | select(.files | keys | any(test("^\\.justcache/[0-9a-f]{64}\\.json$")))] | length' "$OUT")
DIRS=$(jq -s '[.[] | select(.dirs | length > 0)] | length' "$OUT")
SYMLINKS=$(jq -s '[.[] | select(.symlinks | length > 0)] | length' "$OUT")
MODES=$(jq -s '[.[] | select(.modes | length > 0)] | length' "$OUT")
LOSSY_IDS=$(sort -u "$RAW.lossy")
if [ -n "$LOSSY_IDS" ]; then
	LOSSY=$(printf '%s\n' "$LOSSY_IDS" | wc -l | tr -d ' ')
	LOSSY_LIST=$(printf '%s\n' "$LOSSY_IDS" | sed 's/^/- `/; s/$/`/')
else
	LOSSY=0
	LOSSY_LIST="None."
fi
VERSION=$(oracle/bin/just --version)
PIN=$(git -C oracle/src rev-parse HEAD)

cat >conformance/corpus/README.md <<README
# Conformance corpus

Generated by \`scripts/record-corpus.sh\`. Do not edit by hand; run \`just corpus\`.

Each line of \`cases.jsonl\` is one call to \`Test::status\` in upstream's
\`tests/\` directory, recorded by \`scripts/recorder.patch\`. The schema is the
\`Case\` type in \`conformance/case.go\`.

| | |
|---|---|
| Oracle version | \`$VERSION\` |
| Oracle commit | \`$PIN\` |
| Total cases | $TOTAL |
| Cases with regex comparisons | $REGEX |
| Cases with JSON responses | $RESPONSE |
| Cases with a path-hashed cache file | $CACHED |
| Cases with empty directories (\`dirs\`) | $DIRS |
| Cases with symbolic links (\`symlinks\`) | $SYMLINKS |
| Cases with file modes outside the convention (\`modes\`) | $MODES |
| Lossy cases (an input that is not valid UTF-8 was left out) | $LOSSY |

The pass counts and the ratchet baseline are recorded by hand in
\`conformance/BASELINE.md\`, which \`just corpus\` does not touch.

## How to read a case

- \`args\` is the full command line. Upstream adds \`--shell bash\` unless a test
  turns that off, so it is already in \`args\`.
- \`stdout\` and \`stderr\` are the expectations after upstream's \`unindent\`. They
  are omitted when the matching \`*_regex\` is set. A regex is the complete
  pattern upstream compiled, including its \`^\` and \`\$\` anchors and \`(?s)\`.
- \`path_extra\` lists directories relative to the case's temporary directory
  (\`.\` is the directory itself). Upstream's \`Test::path\` **replaces**
  \`PATH\`, so a runner sets \`PATH\` to exactly these directories, resolved
  against its temporary directory and joined with the platform's path list
  separator. It does not prepend to the inherited \`PATH\`. The name is
  historical. The field is used only when every element of upstream's \`PATH\`
  lay inside the temporary directory; then \`PATH\` is removed from \`env\`.
  Otherwise \`PATH\` stays in \`env\` (with placeholders, see below) and
  \`path_extra\` is empty.
- Absolute paths of the machine that recorded the corpus are replaced by
  placeholders in every string of a case (\`files\` contents, \`args\`, \`env\`,
  \`stdin\`, \`stdout\`, \`stderr\`, both regexes, decoded \`expected_files\`
  contents, and \`response\`). A runner substitutes them back before it runs
  the case and again in the expectations:
  - \`@@TEMPDIR@@\` is the case's temporary directory. The runner must create
    it with symbolic links resolved (on macOS \`/var\` is \`/private/var\`), so
    that the plain and the canonical spelling are the same string.
  - \`@@TEMPDIR_PARENT@@\` is the directory that contains it.
  - \`@@JUST_EXECUTABLE@@\` is the absolute path of the binary under test.

  Inside \`stdout_regex\` and \`stderr_regex\` the runner inserts the
  regex-quoted path (Go's \`regexp.QuoteMeta\`). Everywhere else it inserts the
  path as it is.
- \`env\` overlays the environment the child inherits; it is not the whole
  environment. Upstream's child inherits the full environment of the test
  process minus every variable whose name starts with \`JUST_\` (\`just()\` in
  upstream's \`tests/lib.rs\` removes them), and \`env\` is applied on top.
- \`files\` holds the regular files of the temporary directory just before
  just ran. By convention a file named \`*.exe\` has mode 0755 (upstream makes
  executables only through \`Test::write_executable\`, which requires the
  suffix) and every other file has mode 0644.
- \`modes\` maps a path in \`files\` to its permission bits as four octal
  digits (for example \`"0400"\`). It lists only the files whose mode differs
  from the convention, so an \`*.exe\` file that upstream left
  non-executable appears here as \`"0644"\`.
- \`dirs\` lists the empty directories in the temporary directory. A
  directory that holds a file or a link is implied by it and is not listed.
- \`symlinks\` maps the path of a symbolic link to its target as upstream
  created it. \`Test::symlink\` makes absolute targets, so most targets
  start with \`@@TEMPDIR@@\`. A target may dangle, and a link may point at a
  directory.
- \`response\` is the value upstream compared with stdout, or \`null\`. The
  key is always present, so in Go a \`null\` decodes to
  \`json.RawMessage("null")\`, not nil; \`Case.HasResponse\` tells the cases
  that compare a JSON response.

## Cases that cannot be reproduced

just names its cache files \`.justcache/<hash>.json\` after a hash of the
justfile's absolute path. A case whose \`files\` contain such a file was
recorded with the recorder's temporary directory in that hash, and no
placeholder can stand for it. The table above counts them. The runner should
treat them as path-dependent.

## What is not recorded

- Tests that run the binary without \`Test::status\`: the test files \`edit\`,
  \`examples\`, \`print\`, \`readme\`, and \`signals\`.
- Entries in the temporary directory that are not regular files,
  directories, or symbolic links, such as the FIFO of \`dotenv::fifo\`.
- The modes of directories and of symbolic links.
- Files whose name or content is not valid UTF-8, and empty directories or
  symbolic links whose name or target is not valid UTF-8. The case is still
  recorded without that input; the table above counts these lossy cases and
  they are listed below.
- Cases whose working directory is not valid UTF-8. They are left out whole.
- Tests compiled only for other platforms (\`windows\`, \`windows_shell\`, and on
  non-Linux systems \`non_unicode\`).

## Lossy cases

Each of these cases lost at least one input that is not valid UTF-8, so it
may behave differently under a runner than it did upstream.

$LOSSY_LIST
README

echo "recorded $TOTAL cases into $OUT"
